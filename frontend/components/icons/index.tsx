type SvgProps = IconProps & { flip?: keyof typeof FLIP };

function Svg({
  size = 24,
  tone = "default",
  accent,
  color,
  style,
  flip,
  children,
  ...rest
}: SvgProps) {
  const svgProps = { ...rest } as Record<string, unknown>;
  delete svgProps.strokeWidth;
  delete svgProps.absoluteStrokeWidth;
  delete svgProps.fill;
  const tint = accent ? ACCENT[accent] : color;
  const opacity = TONE[tone];
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="currentColor"
      focusable="false"
      aria-hidden={rest["aria-label"] ? undefined : true}
      {...svgProps}
      style={{ color: tint, opacity: opacity === 1 ? undefined : opacity, ...style }}
    >
      {flip ? <g transform={FLIP[flip]}>{children}</g> : children}
    </svg>
  );
}

function S({ children, ...p }: React.SVGProps<SVGGElement>) {
  return (
    <g
      fill="none"
      stroke="currentColor"
      strokeWidth={3}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...p}
    >
      {children}
    </g>
  );
}

function Knock({
  shape,
  children,
}: {
  shape: React.ReactNode | ((c: string) => React.ReactNode);
  children: React.ReactNode;
}) {
  const draw = (c: string) => (typeof shape === "function" ? shape(c) : shape);
  const id = "k" + React.useId().replace(/[^a-zA-Z0-9]/g, "");
  return (
    <>
      <mask id={id} maskUnits="userSpaceOnUse" x="0" y="0" width="24" height="24">
        <g fill="#fff">{draw("#fff")}</g>
        <g fill="none" stroke="#000" strokeWidth={3} strokeLinecap="round" strokeLinejoin="round">
          {children}
        </g>
      </mask>
      <g mask={`url(#${id})`}>{draw("currentColor")}</g>
    </>
  );
}

