/**
 * Rangée de moyens de paiement. Chaque logo est dans une pastille blanche de
 * taille fixe : impossible qu'un logo empiète sur son voisin, et les logos
 * noirs (Apple Pay) restent lisibles en mode sombre.
 */
export function PaymentLogos({
  size = "md",
  className = "",
}: {
  size?: keyof typeof CHIP_SIZES;
  className?: string;
}) {
  const s = CHIP_SIZES[size];
  return (
    <ul className={`flex flex-wrap items-center justify-center ${s.gap} ${className}`}>
      {PAYMENT_METHODS.map(({ id, label, Logo, wide }) => (
        <li
          key={id}
          title={label}
          className={`flex shrink-0 items-center justify-center border border-black/10 bg-white shadow-sm ${wide ? s.wide : s.chip}`}
        >
          <Logo />
        </li>
      ))}
    </ul>
  );
}

